package com.wildlands.felling;

/**
 * Что находится в ячейке мира с точки зрения падающей части дерева. Ячейки самой падающей части
 * (в её текущем положении) считаются свободными: это учитывает {@link FallSim}.
 */
public interface Collider {
    int FREE = 0;
    /** Чужая листва: сминается, но своя листва в неё не входит. */
    int FOREIGN_LEAF = 1;
    /** Чужая тонкая ветка: ломается, если по ней ударило. */
    int FOREIGN_THIN = 2;
    /** Чужая толстая древесина (ствол другого дерева). */
    int FOREIGN_THICK = 3;
    /** Земля, камень, постройка, незагруженная область. */
    int SOLID = 4;
    /** В ячейке стоит игрок: его дерево не давит, а останавливается. */
    int PLAYER = 5;

    int classify(int x, int y, int z);
}
